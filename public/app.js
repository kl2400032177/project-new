function applyLanguage(lang) {
  state.lang = lang;
  localStorage.setItem('manaRaituLang', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = translations[lang][key] || translations.en[key] || key;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    node.placeholder = translations[lang][key] || translations.en[key] || key;
  });

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });

  renderProducts();
  renderFaq();
  renderTestimonials();
  renderFarmers();
  renderDashboard();
  renderCart();
  updateAccountButton();
}

function renderCategoryFilters() {
  const container = document.getElementById('categoryFilters');
  const categories = ['all', 'vegetables', 'fruits', 'organic', 'grains', 'dairy'];

  container.innerHTML = categories.map((category) => {
    const label = translations[state.lang][category] || category;
    return `<button class="filter-chip ${state.category === category ? 'active' : ''}" data-category="${category}">${label}</button>`;
  }).join('');

  container.querySelectorAll('[data-category]').forEach((button) => {
    button.addEventListener('click', () => {
      state.category = button.dataset.category;
      renderCategoryFilters();
      renderProducts();
    });
  });
}

function productText(product, field) {
  return state.lang === 'te' ? productTextTe[product.id][field] : product[field];
}

function renderProducts() {
  const grid = document.getElementById('productGrid');
  const filtered = products.filter((product) => {
    const matchesCategory = state.category === 'all' || product.category === state.category;
    const localized = productTextTe[product.id];
    const searchText = `${product.name} ${product.farmer} ${product.location} ${localized.name} ${localized.farmer} ${localized.location}`.toLowerCase();
    return matchesCategory && searchText.includes(state.searchTerm);
  });

  grid.innerHTML = filtered.map((product) => {
    const name = productText(product, 'name');
    return `
    <article class="product-card">
      <div class="product-visual">
        <img class="product-image" src="${product.image}" alt="${name}" loading="eager" />
        <span class="product-image-fallback" aria-hidden="true" hidden>${product.icon}</span>
      </div>
      <div class="product-body">
        <div class="product-top">
          <span class="badge-tag">${translations[state.lang][product.category]}</span>
          <span class="badge-tag">${product.rating}</span>
        </div>
        <h3>${name}</h3>
        <p class="product-meta">${productText(product, 'farmer')}</p>
        <p class="product-detail">${productText(product, 'location')}</p>
        <div class="product-footer">
          <div class="price">₹${product.price}<small> / ${productText(product, 'unit')}</small></div>
          <button class="btn btn-primary small" type="button" data-add-product="${product.id}">${translations[state.lang].addToCart}</button>
        </div>
        ${product.imageCredit ? `<small class="photo-credit"><a href="https://www.formulatehealth.com/" target="_blank" rel="noopener noreferrer">${state.lang === 'te' ? 'ఫోటో:' : 'Photo:'} formulatehealth</a> · <a href="https://creativecommons.org/licenses/by/2.0/" target="_blank" rel="noopener noreferrer">CC BY 2.0</a></small>` : ''}
      </div>
    </article>
  `;
  }).join('');

  grid.querySelectorAll('.product-image').forEach((image) => {
    image.addEventListener('error', () => {
      image.hidden = true;
      image.nextElementSibling.hidden = false;
      image.parentElement.classList.add('image-failed');
    }, { once: true });
  });
}

