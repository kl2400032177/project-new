function wirePageActions() {
  document.querySelector('[data-i18n="shopNow"]').addEventListener('click', () => {
    document.getElementById('products').scrollIntoView({ behavior: 'smooth' });
  });

  document.querySelector('[data-i18n="joinFarmer"]').addEventListener('click', () => {
    document.getElementById('farmer').scrollIntoView({ behavior: 'smooth' });
  });

  document.querySelector('[data-i18n="dashboardAction"]').addEventListener('click', () => {
    document.getElementById('dashboardGrid').scrollIntoView({ behavior: 'smooth', block: 'center' });
  });

  const locationInput = document.getElementById('locationSearch');
  const search = () => {
    const query = locationInput.value.trim();
    const isPinCode = /^\d{6}$/.test(query);

    if (/^\d+$/.test(query) && !/^[1-8]\d{5}$/.test(query)) {
      showToast(translations[state.lang].invalidPinMessage);
      return;
    }

    if (isPinCode) {
      if (query[0] !== '5') {
        state.searchTerm = '__outside_demo_area__';
        showToast(translations[state.lang].outsideDemoAreaMessage);
      } else {
        const area = pinCodeAreas[query.slice(0, 3)];
        state.searchTerm = area ? area.toLowerCase() : '';
        const areaName = state.lang === 'te' ? pinCodeAreasTe[area] : area;
        const notice = area
          ? translations[state.lang].pinAreaMessage.replace('{area}', areaName)
          : translations[state.lang].regionalCatalogMessage;
        showToast(notice);
      }
    } else {
      state.searchTerm = query.toLowerCase();
    }

    state.category = 'all';
    renderCategoryFilters();
    renderProducts();
    renderFarmers();
    if (!document.querySelector('#productGrid .product-card')) showToast(translations[state.lang].noDemoProductsMessage);
    document.getElementById('products').scrollIntoView({ behavior: 'smooth' });
  };

  document.querySelector('.location-search button').addEventListener('click', search);
  locationInput.addEventListener('keydown', (event) => {
    if (event.key === 'Enter') search();
  });

  document.getElementById('navMenuToggle').addEventListener('click', (event) => {
    const expanded = event.currentTarget.getAttribute('aria-expanded') === 'true';
    event.currentTarget.setAttribute('aria-expanded', String(!expanded));
    event.currentTarget.setAttribute('aria-label', expanded ? 'Open navigation' : 'Close navigation');
    document.getElementById('mainNav').classList.toggle('is-open', !expanded);
  });

  document.querySelectorAll('#mainNav a').forEach((link) => {
    link.addEventListener('click', () => {
      document.getElementById('mainNav').classList.remove('is-open');
      const menuToggle = document.getElementById('navMenuToggle');
      menuToggle.setAttribute('aria-expanded', 'false');
      menuToggle.setAttribute('aria-label', 'Open navigation');
    });
  });

  document.getElementById('farmerGrid').addEventListener('click', (event) => {
    const button = event.target.closest('[data-farmer-search]');
    if (!button) return;
    locationInput.value = button.dataset.farmerSearch;
    state.searchTerm = button.dataset.farmerSearch.toLowerCase();
    renderProducts();
    document.getElementById('products').scrollIntoView({ behavior: 'smooth' });
  });

  document.querySelectorAll('.footer-bottom a[href="#"]').forEach((link) => {
    link.addEventListener('click', (event) => {
      event.preventDefault();
      showToast('This information page is not available in the demo yet.');
    });
  });
}

function showToast(message) {
  const toast = document.getElementById('toast');
  toast.textContent = message;
  toast.classList.add('visible');
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => toast.classList.remove('visible'), 3200);
}

